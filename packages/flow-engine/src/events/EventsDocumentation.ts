/** Markdown section about the lifecycle events the flow daemon publishes to the queue, embedded in the generated flow documentation. */
export class EventsDocumentation {
	public generate(): string {
		return [
			'## Section 9: Events',
			'',
			'The flow daemon publishes lifecycle events to the queue. Wait on them with `queue wait` instead of polling `flow status`.',
			'',
			'| Event | Fires when |',
			'| --- | --- |',
			'| `flow.execution.started` | The first step of an execution is dispatched (once per execution; not repeated by `flow resume`) |',
			'| `flow.execution.completed` | Every step completed. A re-queued or retried execution is not completed |',
			'| `flow.execution.failed` | The execution failed for good (also when it fails on an unanswered `user_intervention`; `flow resume` may reopen it) |',
			'| `flow.step.started` | A step attempt starts; a retry fires it again with `attempt` + 1 |',
			'| `flow.step.completed` | A step attempt that ran completed (skipped steps publish nothing) |',
			'| `flow.step.failed` | A step attempt failed; if it is retried, `flow.step.started` follows with `attempt` + 1 |',
			'',
			'### Payload',
			'',
			'| Field | Content |',
			'| --- | --- |',
			'| `executionId`, `flowId` | Always |',
			'| `stepId`, `attempt` | Step events only; `attempt` starts at 1 |',
			'| `status` | `running`, `completed` or `failed` |',
			'| `startedAt`, `completedAt`, `durationMs` | ISO timestamps and milliseconds; completion fields only once finished |',
			'| `projectRoot` | Project the execution belongs to, when it has one |',
			'| `error` | Failed events only: first line of the (secret-masked) error, at most 200 characters |',
			'',
			'No inputs, environment values, tokens, step outputs, stdout or stderr are ever published.',
			'',
			'### Wait for an execution',
			'',
			'`queue wait` matches exact event names (no wildcards; wildcards exist only in `subscribers.yml`). Several `--when` must all hold. To wait for completed OR failed, run two waits.',
			'',
			'```',
			'queue wait flow.execution.completed --when "payload.executionId=<id>" --since 5m --json',
			'queue wait flow.execution.failed --when "payload.executionId=<id>" --since 5m --json',
			'queue wait flow.step.failed --when "payload.executionId=<id>" --when "payload.stepId=<step>" --json',
			'```',
			'',
			'### Notes',
			'',
			'- Needs the `queue` CLI on the PATH of the flow daemon; the queue daemon is started on demand if stopped. The daemon log (`flow logs`) states at start whether events are enabled or unavailable, and why.',
			'- `FLOW_QUEUE_EVENTS=0` in the flow daemon environment switches events off.',
			'- Delivery is best effort: a failure to publish never affects a run.',
			'- In `subscribers.yml`, `flow.>` matches all flow events and `flow.step.*` all step events (`flow.*` matches nothing).',
		].join('\n');
	}
}
