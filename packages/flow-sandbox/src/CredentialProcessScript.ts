import { SandboxError } from './SandboxError';

/** Environment variable that carries the placeholder of the endpoint secret inside the sandbox. */
export const CREDENTIAL_TOKEN_VARIABLE = 'FLOW_CREDENTIAL_TOKEN';

/**
 * The bash script placed in the VM that AWS tools run as `credential_process = <script> <alias>`.
 * It asks the HostCredentialEndpoint (through `host.docker.internal`) for the credentials of the alias,
 * sending `Authorization: Bearer $FLOW_CREDENTIAL_TOKEN`. That variable holds the PLACEHOLDER; the sbx proxy
 * swaps in the real secret on the way out, so no secret and no AWS key is ever in the VM.
 *
 * On any failure it prints an actionable message to stderr (the endpoint's message when it answered) and exits 1,
 * which is where the AWS SDK of the tool shows credential_process errors.
 */
export class CredentialProcessScript {
	static render(endpointPort: number): string {
		if (!Number.isInteger(endpointPort) || endpointPort < 1 || endpointPort > 65535) {
			throw new SandboxError(
				'invalid-argument',
				`The credential script needs the endpoint port (1 to 65535), got ${endpointPort}. Start the HostCredentialEndpoint first.`
			);
		}
		return [
			'#!/bin/bash',
			'# Generated by flow-sandbox. AWS credential_process helper: prints the credential document of the profile alias in $1.',
			'set -u',
			'alias_name="${1:-}"',
			'if [[ ! "$alias_name" =~ ^[A-Za-z0-9_-]{1,64}$ ]]; then',
			'  echo "flow credential_process: expected a profile alias as the first argument (letters, digits, _ and -)" >&2',
			'  exit 1',
			'fi',
			`if [ -z "\${${CREDENTIAL_TOKEN_VARIABLE}:-}" ]; then`,
			`  echo "flow credential_process: ${CREDENTIAL_TOKEN_VARIABLE} is not set in the environment of the tool. Pass it with the step environment (the wrapper provides it)." >&2`,
			'  exit 1',
			'fi',
			'body_file="$(mktemp)"',
			'trap \'rm -f "$body_file"\' EXIT',
			'status="$(curl -sS -m 30 -o "$body_file" -w \'%{http_code}\' \\',
			`  -H "Authorization: Bearer \${${CREDENTIAL_TOKEN_VARIABLE}}" \\`,
			`  "http://host.docker.internal:${endpointPort}/credentials?profile=\${alias_name}")" || {`,
			`  echo "flow credential_process: cannot reach the credential endpoint on host.docker.internal:${endpointPort}. Is the wrapper running and is its network rule (localhost:${endpointPort}) still in place?" >&2`,
			'  exit 1',
			'}',
			'if [ "$status" != "200" ]; then',
			'  echo "flow credential_process: the credential endpoint answered HTTP $status: $(cat "$body_file")" >&2',
			'  exit 1',
			'fi',
			'cat "$body_file"',
			'',
		].join('\n');
	}
}
